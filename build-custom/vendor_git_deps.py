#!/usr/bin/env python3
"""Vendor the git-sourced Flutter deps into build-custom/vendor/ and emit
flutter/pubspec_overrides.yaml pointing at the local checkouts.

Why: `flutter pub get` runs git under dart, and dart-spawned children cannot
start Git for Windows' MSYS sh.exe on this machine (NtCreateDirectoryObject
0xC0000022). Git's *local* transport always goes through sh, so pub's
cache->temp clone step dies. Running this script from a normal shell clones the
same pinned revisions, then pub only needs https for hosted packages.
"""

import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
PUBSPEC = os.path.join(REPO, "flutter", "pubspec.yaml")
VENDOR = os.path.join(HERE, "vendor")
OVERRIDES = os.path.join(REPO, "flutter", "pubspec_overrides.yaml")

DEP_RE = re.compile(
    r"^  ([A-Za-z0-9_]+):\n"
    r"(?:    git:\n"
    r"      url: (\S+)\n"
    r"(?:      path: (\S+)\n)?"
    r"      ref: (\S+)\n)",
    re.M,
)


def git(args, cwd=None):
    r = subprocess.run(["git"] + args, cwd=cwd, capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit("git %s failed:\n%s" % (" ".join(args), r.stderr.strip()))
    return r.stdout.strip()


def deps():
    with open(PUBSPEC, encoding="utf-8") as f:
        src = f.read()
    return [(m.group(1), m.group(2), m.group(3) or ".", m.group(4)) for m in DEP_RE.finditer(src)]


def main():
    os.makedirs(VENDOR, exist_ok=True)
    rows = []
    for name, url, subpath, ref in deps():
        repo_dir = os.path.join(VENDOR, name)
        git_dir = os.path.join(repo_dir, ".git")
        if os.path.isdir(git_dir):
            head = git(["rev-parse", "HEAD"], cwd=repo_dir)
            if head != ref:
                git(["fetch", "--quiet", "origin", ref], cwd=repo_dir)
                git(["checkout", "--quiet", "--detach", ref], cwd=repo_dir)
                head = git(["rev-parse", "HEAD"], cwd=repo_dir)
        else:
            print("cloning %-28s %s" % (name, url))
            git(["clone", "--quiet", url, repo_dir])
            git(["checkout", "--quiet", "--detach", ref], cwd=repo_dir)
            head = git(["rev-parse", "HEAD"], cwd=repo_dir)
        if head != ref:
            sys.exit("%s: checked out %s, expected %s" % (name, head, ref))
        pkg = os.path.join(repo_dir, subpath.replace("/", os.sep))
        if not os.path.isfile(os.path.join(pkg, "pubspec.yaml")):
            sys.exit("%s: no pubspec.yaml under %s" % (name, pkg))
        rel = os.path.relpath(pkg, os.path.dirname(OVERRIDES)).replace("\\", "/")
        rows.append((name, ref[:12], rel))
        print("ok       %-28s %s" % (name, ref[:12]))

    # A pubspec_overrides.yaml replaces pubspec.yaml's whole dependency_overrides
    # block, so carry the existing entries over or their pins are lost (intl:
    # dash_chat_2 asks for ^0.18.0, the app overrides it to ^0.19.0).
    with open(PUBSPEC, encoding="utf-8") as f:
        pubspec_lines = f.read().splitlines()
    existing = []
    inside = False
    for line in pubspec_lines:
        if line.startswith("dependency_overrides:"):
            inside = True
            continue
        if inside:
            if not line.strip():
                continue
            if not line.startswith(" "):
                break
            existing.append(line)

    body = [
        "# Generated by build-custom/vendor_git_deps.py -- do not edit by hand.",
        "# See that file for why git deps are vendored instead of fetched by pub.",
        "dependency_overrides:",
    ]
    body += existing
    body += ["  %s:\n    path: %s" % (n, p) for n, _, p in rows]
    with open(OVERRIDES, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(body) + "\n")
    print("wrote %s (%d overrides)" % (OVERRIDES, len(rows)))


if __name__ == "__main__":
    main()
