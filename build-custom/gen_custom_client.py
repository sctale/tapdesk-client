#!/usr/bin/env python3
"""Generate the signed custom-client config for our RustDesk fork.

RustDesk's custom-client mechanism (src/common.rs read_custom_client) expects
base64( ed25519_signature(64) || json ) verified against a public key compiled
into the binary. Upstream ships only *their* public key, so a fork that wants
its own preset must swap that constant for its own -- `init` prints the exact
line to paste.

Layout:
  build-custom/custom_client.json          the config, edit this
  build-custom/keys/sign.key               ed25519 seed, base64 (gitignored, keep it)
  build-custom/out/custom_client.txt       signed+base64 payload (desktop: next to exe)
  flutter/lib/brand/custom_client_config.dart  same payload as a Dart const (android)

Usage: python3 build-custom/gen_custom_client.py init   # once
       python3 build-custom/gen_custom_client.py        # every build
"""

import base64
import json
import os
import sys

try:
    from nacl.signing import SigningKey, VerifyKey
    from nacl.exceptions import BadSignatureError
except ImportError:
    sys.exit("pynacl is required: python3 -m pip install pynacl")

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
CONFIG = os.path.join(HERE, "custom_client.json")
KEY_DIR = os.path.join(HERE, "keys")
KEY_FILE = os.path.join(KEY_DIR, "sign.key")
OUT_DIR = os.path.join(HERE, "out")
PAYLOAD_TXT = os.path.join(OUT_DIR, "custom_client.txt")
DART_FILE = os.path.join(REPO, "flutter", "lib", "brand", "custom_client_config.dart")

PLACEHOLDER_MARK = "CHANGE_ME"


def load_signing_key():
    if not os.path.isfile(KEY_FILE):
        sys.exit("no signing key at %s -- run: gen_custom_client.py init" % KEY_FILE)
    with open(KEY_FILE, encoding="utf-8") as f:
        return SigningKey(base64.b64decode(f.read().strip()))


def pubkey_b64(sk):
    return base64.b64encode(sk.verify_key.encode()).decode()


def do_init():
    if os.path.isfile(KEY_FILE):
        sk = load_signing_key()
        print("key already exists, public key below")
    else:
        os.makedirs(KEY_DIR, exist_ok=True)
        sk = SigningKey.generate()
        with open(KEY_FILE, "w", encoding="utf-8", newline="\n") as f:
            f.write(base64.b64encode(bytes(sk)).decode() + "\n")
        os.chmod(KEY_FILE, 0o600)
        print("wrote %s" % KEY_FILE)
    print("\nPut this public key into src/common.rs read_custom_client() as KEY:")
    print('    const KEY: &str = "%s";' % pubkey_b64(sk))


def read_config():
    with open(CONFIG, encoding="utf-8") as f:
        cfg = json.load(f)
    raw = json.dumps(cfg, ensure_ascii=False, separators=(",", ":")).encode()
    if PLACEHOLDER_MARK in raw.decode():
        sys.exit(
            "%s still has %s placeholders (app name / id server / relay / key).\n"
            "Fill it in before emitting a client config." % (CONFIG, PLACEHOLDER_MARK)
        )
    return cfg, raw


def main():
    sk = load_signing_key()
    cfg, raw = read_config()
    signed = bytes(sk.sign(raw).signature) + raw
    payload = base64.b64encode(signed).decode()

    # round-trip with the same primitive the app uses (libsodium crypto_sign)
    try:
        VerifyKey(sk.verify_key.encode()).verify(signed[64:], signed[:64])
    except BadSignatureError:
        sys.exit("self-verification failed, refusing to emit")

    os.makedirs(OUT_DIR, exist_ok=True)
    with open(PAYLOAD_TXT, "w", encoding="utf-8", newline="\n") as f:
        f.write(payload + "\n")

    os.makedirs(os.path.dirname(DART_FILE), exist_ok=True)
    with open(DART_FILE, "w", encoding="utf-8", newline="\n") as f:
        f.write(
            "// Generated by build-custom/gen_custom_client.py -- do not edit by hand.\n"
            "// base64(ed25519 sig || custom_client.json), see that script for the format.\n"
            "const String kCustomClientConfig =\n"
            '    "%s";\n' % payload
        )

    print("app-name    : %s" % cfg.get("app-name"))
    print("conn-type   : %s (%s)" % (cfg.get("conn-type"), "controller only" if cfg.get("conn-type") == "outgoing" else "both roles"))
    for group in ("default-settings", "override-settings"):
        for k, v in cfg.get(group, {}).items():
            print("%s: %s" % (k.ljust(22), v))
    print("payload     : %d bytes -> %s" % (len(payload), os.path.relpath(PAYLOAD_TXT, REPO)))
    print("dart const  : %s" % os.path.relpath(DART_FILE, REPO))


if __name__ == "__main__":
    _args = [a for a in sys.argv[1:] if a != "init"]
    if _args:
        # allow signing a different json without touching the committed one
        CONFIG = os.path.abspath(_args[0])
    if "init" in sys.argv[1:]:
        do_init()
    else:
        main()
